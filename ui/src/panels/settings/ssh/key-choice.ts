import { sshKeyCreateInput, sshKeyImportInput, type SshKey } from '@seti/shared'
import { apiPost } from '@/api'

/** The select value that makes a key in the host form; key ids are UUIDs, so it never clashes. */
export const NEW_KEY = 'new'

/** A host form's key: an existing key's id, a new key to make on save, or '' for none yet. */
export interface KeyChoice {
  keyId: string
  name: string
  paste: boolean
  privateKey: string
}

export const keyChoice = (keyId: string | null): KeyChoice => ({
  keyId: keyId ?? '',
  name: '',
  paste: false,
  privateKey: '',
})

/** Whether the choice names a key, or enough to make one. */
export const keyChosen = (choice: KeyChoice) =>
  choice.keyId === NEW_KEY ? choice.name.trim() !== '' : choice.keyId !== ''

/** The chosen key's id, generating or importing a new key first; throws what to show on bad input. */
export async function resolveKey(choice: KeyChoice): Promise<string> {
  if (choice.keyId !== NEW_KEY) {
    return choice.keyId
  }
  const parsed = choice.paste
    ? sshKeyImportInput.safeParse({ name: choice.name, private_key: choice.privateKey })
    : sshKeyCreateInput.safeParse({ name: choice.name })
  if (!parsed.success) {
    throw new Error(parsed.error.issues[0]?.message ?? 'Check the key')
  }
  const key = await apiPost<SshKey>(choice.paste ? '/ssh/keys/import' : '/ssh/keys', parsed.data)
  return key.id
}

export function sourceText(key: SshKey): string {
  switch (key.source) {
    case 'generated':
      return 'Generated by Seti'
    case 'imported':
      return 'Pasted, sealed by Seti'
    case 'file':
      return `Read from ${key.path ?? 'a file'}`
  }
}
