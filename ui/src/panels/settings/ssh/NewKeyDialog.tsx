import { sshKeyCreateInput, sshKeyFileInput, sshKeyImportInput, type SshKey } from '@seti/shared'
import { FileKey, Plus, Upload } from 'lucide-react'
import { useState } from 'react'
import { toast } from 'sonner'
import { apiPost, errorText } from '@/api'
import { CrudEditDialog, Field } from '@/components/crud/CrudForm'
import { Input } from '@/components/ui/input'
import { NativeSelect, NativeSelectOption } from '@/components/ui/native-select'
import { PathField, PrivateKeyField } from './key-fields'

type Source = 'generate' | 'paste' | 'file'

const SOURCES: { id: Source; label: string }[] = [
  { id: 'generate', label: 'Generate a new key' },
  { id: 'paste', label: 'Paste a private key' },
  { id: 'file', label: 'Key file on this machine' },
]

const isSource = (value: string): value is Source => SOURCES.some((source) => source.id === value)

const SUBMIT: Record<Source, { label: string; busy: string; done: string; icon: typeof Plus }> = {
  generate: { label: 'Generate', busy: 'Generating...', done: 'Key generated', icon: Plus },
  paste: { label: 'Import', busy: 'Importing...', done: 'Key imported', icon: Upload },
  file: { label: 'Add', busy: 'Adding...', done: 'Key added', icon: FileKey },
}

function parseNewKey(source: Source, input: { name: string; comment: string; privateKey: string; file: string }) {
  switch (source) {
    case 'generate':
      return { path: '/ssh/keys', parsed: sshKeyCreateInput.safeParse({ name: input.name, comment: input.comment }) }
    case 'paste':
      return {
        path: '/ssh/keys/import',
        parsed: sshKeyImportInput.safeParse({
          name: input.name,
          comment: input.comment,
          private_key: input.privateKey,
        }),
      }
    case 'file':
      return { path: '/ssh/keys/file', parsed: sshKeyFileInput.safeParse({ name: input.name, path: input.file }) }
  }
}

/** A new key: generated by Seti, a pasted private key Seti seals, or a key file on this machine. */
export function NewKeyDialog({ onAdded, onClose }: { onAdded: () => void; onClose: () => void }) {
  const [name, setName] = useState('')
  const [comment, setComment] = useState('')
  const [privateKey, setPrivateKey] = useState('')
  const [file, setFile] = useState('')
  const [source, setSource] = useState<Source>('generate')
  const [busy, setBusy] = useState(false)
  const submit = async () => {
    const { path, parsed } = parseNewKey(source, { name, comment, privateKey, file })
    if (!parsed.success) {
      toast.error(parsed.error.issues[0]?.message ?? 'Check the key')
      return
    }
    setBusy(true)
    try {
      await apiPost<SshKey>(path, parsed.data)
      toast.success(SUBMIT[source].done)
      onAdded()
      onClose()
    } catch (e) {
      toast.error(errorText(e))
    } finally {
      setBusy(false)
    }
  }
  return (
    <CrudEditDialog
      open
      title="New SSH key"
      onCancel={onClose}
      onSave={() => void submit()}
      saving={busy}
      canSave={name.trim() !== ''}
      saveLabel={SUBMIT[source].label}
      savingLabel={SUBMIT[source].busy}
      saveIcon={SUBMIT[source].icon}
    >
      <Field label="Source" full>
        <NativeSelect
          aria-label="Key source"
          className="w-full"
          value={source}
          onChange={(event) => {
            const next = event.target.value
            setSource(isSource(next) ? next : 'generate')
          }}
        >
          {SOURCES.map((entry) => (
            <NativeSelectOption key={entry.id} value={entry.id}>
              {entry.label}
            </NativeSelectOption>
          ))}
        </NativeSelect>
      </Field>
      <Field label="Name">
        <Input
          aria-label="Key name"
          autoComplete="off"
          placeholder="ops"
          value={name}
          onChange={(event) => {
            setName(event.target.value)
          }}
        />
      </Field>
      {source !== 'file' && (
        <Field label="Comment">
          <Input
            aria-label="Key comment"
            autoComplete="off"
            placeholder={name.trim() === '' ? 'Optional' : name.trim()}
            value={comment}
            onChange={(event) => {
              setComment(event.target.value)
            }}
          />
        </Field>
      )}
      {source === 'paste' && (
        <Field label="Private key" full>
          <PrivateKeyField value={privateKey} onChange={setPrivateKey} />
        </Field>
      )}
      {source === 'file' && (
        <Field label="Key file">
          <PathField value={file} onChange={setFile} />
        </Field>
      )}
      <p className="col-span-full text-xs text-muted-foreground">
        The comment ends the public key, as authorized_keys shows it; empty uses the name. Seti never shows a private
        key again.
      </p>
    </CrudEditDialog>
  )
}
