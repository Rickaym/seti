/** Pollers are channels too: a webhook's secret and mapping stay empty on them. */
export const POLLER_CHANNELS = `
ALTER TABLE channel ADD COLUMN source TEXT NOT NULL DEFAULT 'webhook' CHECK (source IN ('webhook', 'poller'));
ALTER TABLE channel ALTER COLUMN secret DROP NOT NULL;

CREATE TABLE channel_poller (
  channel_id TEXT PRIMARY KEY REFERENCES channel(id) ON DELETE CASCADE,
  script TEXT NOT NULL,
  preset TEXT NOT NULL,
  interval_s INTEGER NOT NULL,
  timeout_s INTEGER NOT NULL,
  extra_hosts TEXT NOT NULL DEFAULT '[]',
  secrets TEXT NOT NULL DEFAULT '[]',
  fingerprint_fields TEXT NOT NULL DEFAULT '[]',
  detect_gone BOOLEAN NOT NULL DEFAULT false,
  enabled BOOLEAN NOT NULL DEFAULT true,
  state TEXT,
  failures INTEGER NOT NULL DEFAULT 0,
  failing BOOLEAN NOT NULL DEFAULT false,
  baseline_at TEXT,
  last_run_at TEXT,
  last_ok_at TEXT,
  next_run_at TEXT
);

CREATE TABLE channel_poller_item (
  channel_id TEXT NOT NULL REFERENCES channel(id) ON DELETE CASCADE,
  key TEXT NOT NULL,
  fingerprint TEXT NOT NULL,
  kind TEXT NOT NULL DEFAULT '',
  title TEXT NOT NULL,
  url TEXT,
  fields TEXT NOT NULL DEFAULT '{}',
  first_seen TEXT NOT NULL,
  last_seen TEXT NOT NULL,
  PRIMARY KEY (channel_id, key)
);
CREATE INDEX channel_poller_item_seen ON channel_poller_item(channel_id, last_seen);

CREATE TABLE channel_poller_run (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  channel_id TEXT NOT NULL REFERENCES channel(id) ON DELETE CASCADE,
  trigger TEXT NOT NULL,
  started_at TEXT NOT NULL,
  duration_ms INTEGER NOT NULL,
  ok BOOLEAN NOT NULL,
  items INTEGER NOT NULL,
  emitted INTEGER NOT NULL,
  invalid TEXT NOT NULL DEFAULT '[]',
  error TEXT,
  logs TEXT NOT NULL DEFAULT '[]'
);
CREATE INDEX channel_poller_run_recent ON channel_poller_run(channel_id, id);
`

/** Runs keep when the schedule wanted them, and stay a month by time so health can be measured. */
export const CHANNEL_RUN_DUE = `
ALTER TABLE channel_poller_run ADD COLUMN due_at TEXT;
ALTER TABLE channel_reminder_run ADD COLUMN due_at TEXT;
CREATE INDEX channel_poller_run_started ON channel_poller_run(channel_id, started_at);
CREATE INDEX channel_reminder_run_started ON channel_reminder_run(channel_id, started_at);
`

/** Events are routed at least once: each records the subscribers it reached, and retries the rest. */
export const CHANNEL_EVENT_ROUTING = `
ALTER TABLE channel_event ADD COLUMN routed_at TEXT, ADD COLUMN route_attempts INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN route_error TEXT, ADD COLUMN retry_at TEXT;
UPDATE channel_event SET routed_at = created_at;
CREATE INDEX channel_event_unrouted ON channel_event(id) WHERE routed_at IS NULL;

CREATE TABLE channel_event_delivery (
  event_id BIGINT NOT NULL REFERENCES channel_event(id) ON DELETE CASCADE,
  subscription_id BIGINT NOT NULL REFERENCES channel_subscription(id) ON DELETE CASCADE,
  delivered_at TEXT NOT NULL,
  PRIMARY KEY (event_id, subscription_id)
);
`
