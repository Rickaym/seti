/** Items for the EA, the tasks it watches, and notification channels with the events they report. */
export const EA_INBOX = `
CREATE TABLE ea_inbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL,
  event TEXT NOT NULL,
  title TEXT NOT NULL,
  body TEXT NOT NULL DEFAULT '',
  url TEXT,
  severity TEXT NOT NULL,
  source TEXT NOT NULL DEFAULT '',
  task_id TEXT REFERENCES task(id) ON DELETE SET NULL,
  timezone TEXT,
  depth INTEGER NOT NULL DEFAULT 0,
  due_at TEXT NOT NULL,
  created_at TEXT NOT NULL,
  delivered_at TEXT,
  delivered_via TEXT,
  acknowledged_at TEXT,
  cancelled_at TEXT,
  entry_id BIGINT REFERENCES ea_history(id) ON DELETE SET NULL
);
CREATE INDEX ea_inbox_pending ON ea_inbox(due_at, id) WHERE delivered_at IS NULL AND cancelled_at IS NULL;
CREATE INDEX ea_inbox_unread ON ea_inbox(id) WHERE delivered_at IS NOT NULL AND acknowledged_at IS NULL;
CREATE INDEX ea_inbox_entry ON ea_inbox(entry_id);
CREATE INDEX ea_inbox_task ON ea_inbox(task_id);

CREATE TABLE ea_watch (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id TEXT NOT NULL UNIQUE REFERENCES task(id) ON DELETE CASCADE,
  note TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL
);

CREATE TABLE channel (
  name TEXT PRIMARY KEY,
  enabled INTEGER NOT NULL,
  last_poll_at TEXT,
  last_ok_at TEXT,
  last_error TEXT,
  updated_at TEXT NOT NULL
);

CREATE TABLE channel_event (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  channel TEXT NOT NULL,
  dedupe_key TEXT NOT NULL,
  source TEXT NOT NULL,
  severity TEXT NOT NULL,
  title TEXT NOT NULL,
  detail TEXT NOT NULL,
  url TEXT,
  subject TEXT,
  state TEXT,
  occurred_at TEXT NOT NULL,
  created_at TEXT NOT NULL,
  UNIQUE (channel, dedupe_key)
);
CREATE INDEX channel_event_recent ON channel_event(channel, id);

CREATE TABLE channel_subject (
  channel TEXT NOT NULL,
  subject TEXT NOT NULL,
  state TEXT NOT NULL,
  changed_at TEXT NOT NULL,
  PRIMARY KEY (channel, subject)
);
`

/**
 * EA messages the user has not seen yet, the questions the EA asks before a tool acts with the
 * user's answer to each, and whether EA messages show as toasts. A question records the EA
 * process and user turn it was asked in, so only a later yes covers it, across restarts too.
 */
export const EA_REPLIES = `
ALTER TABLE ea_history ADD COLUMN unseen BOOLEAN NOT NULL DEFAULT false;
CREATE INDEX ea_history_unseen ON ea_history(id) WHERE unseen;

CREATE TABLE ea_ask (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tool TEXT NOT NULL,
  args TEXT NOT NULL,
  summary TEXT NOT NULL,
  gate_key TEXT NOT NULL,
  ask_epoch TEXT NOT NULL,
  ask_turn INTEGER NOT NULL,
  entry_id BIGINT REFERENCES ea_history(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  decision TEXT,
  decided_at TEXT,
  taken_at TEXT,
  outcome TEXT,
  detail TEXT
);
CREATE INDEX ea_ask_entry ON ea_ask(entry_id);
CREATE INDEX ea_ask_open ON ea_ask(gate_key) WHERE decision IS NULL;
CREATE INDEX ea_ask_answered ON ea_ask(id) WHERE decision IS NOT NULL AND taken_at IS NULL;

ALTER TABLE notification_settings ADD COLUMN ea_replies BOOLEAN NOT NULL DEFAULT true;
`

