/** Searchable task and PR text; embeddings are plain arrays, indexed only where pgvector is. */
export const EA_INDEX = `
CREATE TABLE ea_doc (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key TEXT NOT NULL UNIQUE,
  scope TEXT NOT NULL,
  kind TEXT NOT NULL,
  task_id TEXT REFERENCES task(id) ON DELETE CASCADE,
  message_id BIGINT,
  pr_url TEXT,
  repo TEXT,
  title TEXT NOT NULL DEFAULT '',
  body TEXT NOT NULL,
  hash TEXT NOT NULL,
  at TEXT NOT NULL,
  tsv TSVECTOR GENERATED ALWAYS AS (to_tsvector('english', title || ' ' || body)) STORED,
  embedding REAL[],
  UNIQUE (scope, hash)
);
CREATE INDEX ea_doc_tsv ON ea_doc USING gin (tsv);
CREATE INDEX ea_doc_task ON ea_doc(task_id, id);
CREATE INDEX ea_doc_pr ON ea_doc(pr_url);
CREATE INDEX ea_doc_unembedded ON ea_doc(id) WHERE embedding IS NULL;

CREATE TABLE ea_index_cursor (
  task_id TEXT PRIMARY KEY REFERENCES task(id) ON DELETE CASCADE,
  message_id BIGINT NOT NULL
);

CREATE INDEX task_message_notable ON task_message(id)
  WHERE kind IN ('input', 'seti') OR (kind = 'sdk' AND (payload::json ->> 'type') = 'result');
`

