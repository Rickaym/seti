/**
 * Third-party mods: installs pinned to a package hash, kept versions, grants, logs, asks, usage
 * and bisect, plus Developer mode, passkey step-up and the mod that wrote a group chat post.
 */
export const MODS_RUNTIME = `
CREATE TABLE mod_install (
  mod_id TEXT PRIMARY KEY,
  source_kind TEXT NOT NULL CHECK (source_kind IN ('folder', 'git', 'dev')),
  source TEXT NOT NULL,
  track TEXT,
  current_hash TEXT NOT NULL,
  pending_hash TEXT,
  pending_reason TEXT CHECK (pending_reason IN ('consent', 'delay')),
  pending_since TEXT,
  update_delay_hours INTEGER NOT NULL DEFAULT 24 CHECK (update_delay_hours BETWEEN 0 AND 168),
  installed_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  CHECK ((pending_hash IS NULL) = (pending_reason IS NULL) AND (pending_hash IS NULL) = (pending_since IS NULL))
);

CREATE TABLE mod_version (
  mod_id TEXT NOT NULL,
  hash TEXT NOT NULL CHECK (hash ~ '^[a-f0-9]{64}$'),
  version TEXT NOT NULL,
  manifest JSONB NOT NULL,
  files BYTEA NOT NULL,
  script_hashes JSONB NOT NULL DEFAULT '{}',
  size INTEGER NOT NULL,
  source_ref TEXT,
  fetched_at TEXT NOT NULL,
  PRIMARY KEY (mod_id, hash)
);

CREATE TABLE mod_grant (
  mod_id TEXT NOT NULL,
  hash TEXT NOT NULL,
  idx INTEGER NOT NULL,
  capability JSONB NOT NULL,
  connection_id TEXT REFERENCES connection(id) ON DELETE SET NULL,
  granted_at TEXT NOT NULL,
  PRIMARY KEY (mod_id, hash, idx)
);

CREATE TABLE mod_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mod_id TEXT NOT NULL,
  at TEXT NOT NULL,
  event_id TEXT,
  kind TEXT NOT NULL CHECK (kind IN ('log', 'error', 'refused', 'system')),
  level TEXT NOT NULL CHECK (level IN ('info', 'warn', 'error')),
  line TEXT NOT NULL
);

CREATE INDEX mod_log_newest ON mod_log(mod_id, id DESC);

CREATE TABLE mod_ask (
  id TEXT PRIMARY KEY,
  mod_id TEXT NOT NULL,
  op TEXT NOT NULL,
  args JSONB NOT NULL,
  summary TEXT NOT NULL,
  created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  decision TEXT CHECK (decision IN ('allow', 'deny')),
  decided_at TEXT,
  outcome TEXT,
  detail JSONB
);

CREATE INDEX mod_ask_open ON mod_ask(mod_id) WHERE decision IS NULL;

CREATE TABLE mod_usage (
  mod_id TEXT NOT NULL,
  day TEXT NOT NULL,
  cpu_ms BIGINT NOT NULL DEFAULT 0,
  events INTEGER NOT NULL DEFAULT 0,
  failures INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (mod_id, day)
);

CREATE TABLE mod_bisect (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  original JSONB NOT NULL,
  suspects JSONB NOT NULL,
  step INTEGER NOT NULL,
  started_at TEXT NOT NULL
);

ALTER TABLE mod_host ADD COLUMN dev_mode BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE auth_session ADD COLUMN stepped_up_at TEXT;
ALTER TABLE team_message ADD COLUMN author_mod_id TEXT;
`
