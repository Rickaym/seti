/** Webhook channels replace the polled ones; their old events and subject states go with them. */
export const WEBHOOK_CHANNELS = `
DROP TABLE channel;
DELETE FROM channel_event;
DELETE FROM channel_subject;

CREATE TABLE channel (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  preset TEXT NOT NULL,
  secret TEXT NOT NULL,
  deliver_to_ea INTEGER NOT NULL,
  mapping TEXT NOT NULL DEFAULT '{}',
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  secret_rotated_at TEXT
);

ALTER TABLE channel_event ADD CONSTRAINT channel_event_channel_fk
  FOREIGN KEY (channel) REFERENCES channel(id) ON DELETE CASCADE;
ALTER TABLE channel_subject ADD CONSTRAINT channel_subject_channel_fk
  FOREIGN KEY (channel) REFERENCES channel(id) ON DELETE CASCADE;

CREATE TABLE channel_delivery (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  channel TEXT NOT NULL REFERENCES channel(id) ON DELETE CASCADE,
  received_at TEXT NOT NULL,
  status TEXT NOT NULL,
  http_status INTEGER NOT NULL,
  reason TEXT NOT NULL,
  delivery_id TEXT,
  event_id BIGINT REFERENCES channel_event(id) ON DELETE SET NULL,
  excerpt TEXT NOT NULL DEFAULT ''
);
CREATE INDEX channel_delivery_recent ON channel_delivery(channel, id);
CREATE INDEX channel_delivery_event ON channel_delivery(event_id);

CREATE TABLE channel_delivery_seen (
  channel TEXT NOT NULL REFERENCES channel(id) ON DELETE CASCADE,
  delivery_id TEXT NOT NULL,
  seen_at TEXT NOT NULL,
  PRIMARY KEY (channel, delivery_id)
);
`

