/** Channels deliver to subscribers, the EA or tasks, instead of to the EA by a switch. */
export const CHANNEL_SUBSCRIPTIONS = `
CREATE TABLE channel_subscription (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  channel_id TEXT NOT NULL REFERENCES channel(id) ON DELETE CASCADE,
  target TEXT NOT NULL CHECK (target IN ('ea', 'task')),
  task_id TEXT REFERENCES task(id) ON DELETE CASCADE,
  events TEXT,
  created_at TEXT NOT NULL,
  CHECK ((target = 'task') = (task_id IS NOT NULL)),
  UNIQUE NULLS NOT DISTINCT (channel_id, target, task_id)
);
CREATE INDEX channel_subscription_task ON channel_subscription(task_id);

INSERT INTO channel_subscription (channel_id, target, task_id, events, created_at)
  SELECT id, 'ea', NULL, NULL, created_at FROM channel WHERE deliver_to_ea = 1;
ALTER TABLE channel DROP COLUMN deliver_to_ea;

ALTER TABLE channel_event ADD COLUMN kind TEXT NOT NULL DEFAULT '';
ALTER TABLE channel_delivery ADD COLUMN routes TEXT NOT NULL DEFAULT '[]';
`

/** The EA hands an act subscription's alerts to an existing agent unasked; tasks always report. */
export const EA_CHANNEL_MODE = `
ALTER TABLE channel_subscription ADD COLUMN mode TEXT NOT NULL DEFAULT 'report'
  CHECK (mode IN ('report', 'act'));
ALTER TABLE channel_subscription ADD CONSTRAINT channel_subscription_task_reports
  CHECK (target = 'ea' OR mode = 'report');
ALTER TABLE ea_inbox ADD COLUMN act BOOLEAN NOT NULL DEFAULT false;
`

