/** Columns keep the order of the SQLite tables they replace, so `SELECT *` rows serialize alike. */
export const INITIAL = `
CREATE TABLE repo (
  id TEXT PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE,
  path TEXT NOT NULL,
  base_branch TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE task (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  repo_id TEXT REFERENCES repo(id) ON DELETE SET NULL,
  cwd TEXT NOT NULL,
  worktree INTEGER NOT NULL DEFAULT 0,
  session_id TEXT,
  status TEXT NOT NULL,
  permission_mode TEXT,
  model TEXT,
  cost_usd DOUBLE PRECISION NOT NULL DEFAULT 0,
  outward_count BIGINT NOT NULL DEFAULT 0,
  last_error TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  source_session_id TEXT,
  input_mode TEXT NOT NULL DEFAULT 'wake',
  sandbox INTEGER NOT NULL DEFAULT 1
);
CREATE UNIQUE INDEX task_source_session ON task(source_session_id);
CREATE INDEX task_updated ON task(updated_at);
CREATE INDEX task_repo_id ON task(repo_id);

CREATE TABLE task_message (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id TEXT NOT NULL REFERENCES task(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  payload TEXT NOT NULL,
  outward TEXT NOT NULL DEFAULT '[]',
  created_at TEXT NOT NULL
);
CREATE INDEX task_message_task ON task_message(task_id, id);
CREATE INDEX task_message_prompt ON task_message(task_id, id) WHERE kind = 'prompt';
CREATE INDEX task_message_sdk_type ON task_message((payload::json ->> 'type'), id) WHERE kind = 'sdk';
CREATE INDEX task_message_sdk_failure ON task_message(id) WHERE kind = 'sdk'
  AND ((payload::json ->> 'error') IS NOT NULL OR (payload::json ->> 'api_error_status') IS NOT NULL);
CREATE INDEX task_message_parent ON task_message(task_id, (payload::json ->> 'parent_tool_use_id'), id)
  WHERE kind = 'sdk';

CREATE TABLE task_repo (
  task_id TEXT NOT NULL REFERENCES task(id) ON DELETE CASCADE,
  repo_id TEXT NOT NULL REFERENCES repo(id) ON DELETE CASCADE,
  position INTEGER NOT NULL,
  dir TEXT NOT NULL,
  PRIMARY KEY (task_id, repo_id)
);
CREATE INDEX task_repo_repo ON task_repo(repo_id);

CREATE TABLE task_pr (
  task_id TEXT NOT NULL REFERENCES task(id) ON DELETE CASCADE,
  pr_url TEXT NOT NULL,
  linked_at TEXT NOT NULL,
  source TEXT NOT NULL,
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  PRIMARY KEY (task_id, pr_url)
);
CREATE INDEX task_pr_url ON task_pr(pr_url);

CREATE TABLE context_pack (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  description TEXT NOT NULL DEFAULT '',
  body TEXT NOT NULL,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE task_context_pack (
  task_id TEXT NOT NULL REFERENCES task(id) ON DELETE CASCADE,
  pack_id TEXT NOT NULL REFERENCES context_pack(id) ON DELETE CASCADE,
  PRIMARY KEY (task_id, pack_id)
);
CREATE INDEX task_context_pack_pack ON task_context_pack(pack_id);

CREATE TABLE seti_plugin (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  path TEXT NOT NULL UNIQUE,
  version TEXT,
  description TEXT NOT NULL DEFAULT '',
  enabled INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL
);

CREATE TABLE task_plugin_optout (
  task_id TEXT NOT NULL REFERENCES task(id) ON DELETE CASCADE,
  plugin_id TEXT NOT NULL REFERENCES seti_plugin(id) ON DELETE CASCADE,
  PRIMARY KEY (task_id, plugin_id)
);
CREATE INDEX task_plugin_optout_plugin ON task_plugin_optout(plugin_id);

CREATE TABLE routine (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  schedule TEXT NOT NULL,
  timezone TEXT NOT NULL,
  prompt TEXT NOT NULL,
  repo_id TEXT REFERENCES repo(id) ON DELETE SET NULL,
  cwd TEXT,
  worktree INTEGER NOT NULL DEFAULT 0,
  ref TEXT,
  enabled INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE INDEX routine_repo_id ON routine(repo_id);

CREATE TABLE routine_run (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  routine_id TEXT NOT NULL REFERENCES routine(id) ON DELETE CASCADE,
  task_id TEXT REFERENCES task(id) ON DELETE SET NULL,
  started_at TEXT NOT NULL,
  outcome TEXT NOT NULL,
  detail TEXT
);
CREATE INDEX routine_run_routine ON routine_run(routine_id, id);
CREATE INDEX routine_run_task ON routine_run(task_id);

CREATE TABLE routine_context_pack (
  routine_id TEXT NOT NULL REFERENCES routine(id) ON DELETE CASCADE,
  pack_id TEXT NOT NULL REFERENCES context_pack(id) ON DELETE CASCADE,
  PRIMARY KEY (routine_id, pack_id)
);
CREATE INDEX routine_context_pack_pack ON routine_context_pack(pack_id);

CREATE TABLE routine_repo (
  routine_id TEXT NOT NULL REFERENCES routine(id) ON DELETE CASCADE,
  repo_id TEXT NOT NULL REFERENCES repo(id) ON DELETE CASCADE,
  position INTEGER NOT NULL,
  PRIMARY KEY (routine_id, repo_id)
);
CREATE INDEX routine_repo_repo ON routine_repo(repo_id);

CREATE TABLE routine_plugin_optout (
  routine_id TEXT NOT NULL REFERENCES routine(id) ON DELETE CASCADE,
  plugin_id TEXT NOT NULL REFERENCES seti_plugin(id) ON DELETE CASCADE,
  PRIMARY KEY (routine_id, plugin_id)
);
CREATE INDEX routine_plugin_optout_plugin ON routine_plugin_optout(plugin_id);

CREATE TABLE audit_event (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at TEXT NOT NULL,
  actor TEXT NOT NULL,
  kind TEXT NOT NULL,
  subject_type TEXT NOT NULL,
  subject_id TEXT,
  summary TEXT NOT NULL,
  detail TEXT NOT NULL DEFAULT '{}',
  prev_hash TEXT,
  hash TEXT
);
CREATE INDEX audit_event_kind ON audit_event(kind, id);
CREATE INDEX audit_event_actor ON audit_event(actor, id);
CREATE INDEX audit_event_at ON audit_event(at);

CREATE TABLE audit_chain (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  anchor_id BIGINT NOT NULL,
  anchor_hash TEXT NOT NULL,
  head_id BIGINT NOT NULL,
  head_hash TEXT NOT NULL
);

CREATE TABLE revision (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at TEXT NOT NULL,
  actor TEXT NOT NULL,
  task_id TEXT REFERENCES task(id) ON DELETE SET NULL,
  object_type TEXT NOT NULL,
  object_id TEXT NOT NULL,
  before TEXT,
  after TEXT,
  reason TEXT
);
CREATE INDEX revision_object ON revision(object_type, object_id, id);
CREATE INDEX revision_task ON revision(task_id);

CREATE TABLE revision_seen (
  object_type TEXT NOT NULL,
  object_id TEXT NOT NULL,
  revision_id BIGINT NOT NULL,
  PRIMARY KEY (object_type, object_id)
);

CREATE TABLE pr_watch (
  pr_url TEXT PRIMARY KEY,
  snapshot TEXT NOT NULL,
  open INTEGER NOT NULL,
  checked_at TEXT NOT NULL
);

CREATE TABLE task_rewind (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id TEXT NOT NULL REFERENCES task(id) ON DELETE CASCADE,
  prompt_message_id BIGINT NOT NULL,
  last_message_id BIGINT NOT NULL,
  message_count INTEGER NOT NULL,
  prompt_text TEXT NOT NULL,
  restore TEXT NOT NULL,
  state TEXT NOT NULL,
  resume_at TEXT,
  drops_turn TEXT,
  reason TEXT,
  files_changed TEXT NOT NULL DEFAULT '[]',
  created_at TEXT NOT NULL
);
CREATE INDEX task_rewind_task ON task_rewind(task_id, id);

CREATE TABLE pr_discovery_cursor (
  task_id TEXT PRIMARY KEY REFERENCES task(id) ON DELETE CASCADE,
  message_id BIGINT NOT NULL
);

CREATE TABLE task_pr_dismissed (
  task_id TEXT NOT NULL REFERENCES task(id) ON DELETE CASCADE,
  pr_url TEXT NOT NULL,
  at TEXT NOT NULL,
  PRIMARY KEY (task_id, pr_url)
);

CREATE TABLE ea_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL,
  message TEXT NOT NULL,
  through_id BIGINT,
  created_at TEXT NOT NULL
);
CREATE INDEX ea_history_kind ON ea_history(kind, id);

CREATE TABLE ea_settings (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  wake_enabled INTEGER NOT NULL,
  wake_phrase TEXT NOT NULL,
  keep_awake_seconds INTEGER NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE sandbox_policy (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  enabled INTEGER NOT NULL,
  allowed_domains TEXT NOT NULL,
  hidden_paths TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
`
