/** Reminders are channels too: a script Seti runs on an interval, whose message is the event. */
export const REMINDER_CHANNELS = `
ALTER TABLE channel DROP CONSTRAINT channel_source_check;
ALTER TABLE channel ADD CONSTRAINT channel_source_check CHECK (source IN ('webhook', 'poller', 'reminder'));

CREATE TABLE channel_reminder (
  channel_id TEXT PRIMARY KEY REFERENCES channel(id) ON DELETE CASCADE,
  script TEXT NOT NULL,
  interval_s INTEGER NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT true,
  state TEXT,
  last_output TEXT,
  failures INTEGER NOT NULL DEFAULT 0,
  failing BOOLEAN NOT NULL DEFAULT false,
  last_run_at TEXT,
  last_ok_at TEXT,
  next_run_at TEXT
);
CREATE INDEX channel_reminder_due ON channel_reminder(next_run_at) WHERE enabled;

CREATE TABLE channel_reminder_run (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  channel_id TEXT NOT NULL REFERENCES channel(id) ON DELETE CASCADE,
  trigger TEXT NOT NULL,
  started_at TEXT NOT NULL,
  duration_ms INTEGER NOT NULL,
  outcome TEXT NOT NULL CHECK (outcome IN ('ok', 'empty', 'error', 'timeout')),
  message TEXT,
  error TEXT,
  logs TEXT NOT NULL DEFAULT '[]'
);
CREATE INDEX channel_reminder_run_recent ON channel_reminder_run(channel_id, id);
`

/** A reminder may run on a cron schedule in a timezone instead of its interval. */
export const REMINDER_CRON = `
ALTER TABLE channel_reminder ADD COLUMN cron TEXT, ADD COLUMN timezone TEXT;
ALTER TABLE channel_reminder ADD CONSTRAINT channel_reminder_cron_zone CHECK ((cron IS NULL) = (timezone IS NULL));
`

/** Routines are gone: cron reminders took over their timing. */
export const DROP_ROUTINES = `
DROP TABLE routine_mcp_server, routine_plugin_optout, routine_repo, routine_context_pack, routine_run, routine;
DELETE FROM revision_seen WHERE object_type = 'routine';
DELETE FROM revision WHERE object_type = 'routine';
`
