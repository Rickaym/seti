/**
 * Every dream of every agent: its night, how it ended, what it cost and changed, and its report.
 * A night has at most one nightly dream per agent; Dream now adds manual ones beside it.
 */
export const DREAM_RUNS = `
CREATE TABLE dream_run (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id TEXT NOT NULL REFERENCES task(id) ON DELETE CASCADE,
  night TEXT NOT NULL,
  kind TEXT NOT NULL,
  state TEXT NOT NULL,
  reason TEXT,
  model TEXT NOT NULL,
  started_at TEXT NOT NULL,
  ended_at TEXT,
  cost_usd DOUBLE PRECISION NOT NULL DEFAULT 0,
  steps INTEGER NOT NULL DEFAULT 0,
  denials INTEGER NOT NULL DEFAULT 0,
  memory_changes INTEGER NOT NULL DEFAULT 0,
  report JSONB
);
CREATE INDEX dream_run_task ON dream_run(task_id, id);
CREATE UNIQUE INDEX dream_run_nightly ON dream_run(task_id, night) WHERE kind = 'nightly';
`

/**
 * Nightly Dreaming: its settings (off until the user turns it on), the agents and workspaces
 * switched out of it, each night's plan, and the planned and retried dreams of a night.
 */
export const DREAM_NIGHTS = `
CREATE TABLE dream_settings (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  enabled BOOLEAN NOT NULL DEFAULT false,
  window_start TEXT NOT NULL DEFAULT '01:00',
  window_end TEXT NOT NULL DEFAULT '05:00',
  zone TEXT,
  model TEXT NOT NULL DEFAULT 'claude-sonnet-5-5',
  dream_budget_usd DOUBLE PRECISION NOT NULL DEFAULT 1,
  night_budget_usd DOUBLE PRECISION NOT NULL DEFAULT 5,
  at_once INTEGER NOT NULL DEFAULT 1,
  updated_at TEXT NOT NULL
);
CREATE TABLE dream_opt_out (
  task_id TEXT UNIQUE REFERENCES task(id) ON DELETE CASCADE,
  workspace_id TEXT UNIQUE REFERENCES workspace(id) ON DELETE CASCADE,
  created_at TEXT NOT NULL,
  CHECK ((task_id IS NULL) <> (workspace_id IS NULL))
);
CREATE TABLE dream_night (
  night TEXT PRIMARY KEY,
  zone TEXT NOT NULL,
  window_start TEXT NOT NULL,
  window_end TEXT NOT NULL,
  state TEXT NOT NULL,
  skipped JSONB NOT NULL DEFAULT '{}',
  created_at TEXT NOT NULL,
  ended_at TEXT
);
ALTER TABLE dream_run ADD COLUMN attempt INTEGER NOT NULL DEFAULT 1, ADD COLUMN not_before TEXT;
CREATE INDEX dream_run_planned ON dream_run(not_before) WHERE state = 'planned';
`

/** Clean-ups dreams propose, and the trash allowed ones move into for `trash_keep`. */
export const DREAM_PROPOSALS = `
ALTER TABLE dream_settings ADD COLUMN cleanups BOOLEAN NOT NULL DEFAULT false;
CREATE TABLE dream_proposal (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id BIGINT NOT NULL REFERENCES dream_run(id) ON DELETE CASCADE,
  task_id TEXT NOT NULL REFERENCES task(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  target TEXT NOT NULL,
  reason TEXT NOT NULL,
  bytes BIGINT NOT NULL DEFAULT 0,
  state TEXT NOT NULL,
  detail TEXT,
  created_at TEXT NOT NULL,
  decided_at TEXT
);
CREATE INDEX dream_proposal_task ON dream_proposal(task_id, id);
CREATE TABLE trash_item (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id TEXT NOT NULL,
  proposal_id BIGINT NOT NULL REFERENCES dream_proposal(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  original_path TEXT NOT NULL,
  trash_path TEXT NOT NULL,
  bytes BIGINT NOT NULL DEFAULT 0,
  meta JSONB NOT NULL DEFAULT '{}',
  created_at TEXT NOT NULL,
  purge_after TEXT NOT NULL,
  restored_at TEXT,
  purged_at TEXT
);
`
