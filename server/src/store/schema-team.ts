import { selfHeaderPattern } from '../team-header.js'

/** The team chat: messages, each task's handle and mute, and what each message did for a task. */
export const TEAM_CHAT = `
CREATE TABLE team_member (
  task_id TEXT PRIMARY KEY REFERENCES task(id) ON DELETE CASCADE,
  handle TEXT NOT NULL UNIQUE,
  muted INTEGER NOT NULL DEFAULT 0,
  updated_at TEXT NOT NULL
);

CREATE TABLE team_message (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author_kind TEXT NOT NULL,
  author_task_id TEXT REFERENCES task(id) ON DELETE SET NULL,
  author_handle TEXT,
  text TEXT NOT NULL,
  mentions TEXT NOT NULL DEFAULT '[]',
  created_at TEXT NOT NULL
);
CREATE INDEX team_message_author ON team_message(author_task_id, id);

CREATE TABLE team_delivery (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id BIGINT NOT NULL REFERENCES team_message(id) ON DELETE CASCADE,
  task_id TEXT NOT NULL REFERENCES task(id) ON DELETE CASCADE,
  author_kind TEXT NOT NULL,
  mode TEXT NOT NULL,
  reason TEXT,
  created_at TEXT NOT NULL
);
CREATE INDEX team_delivery_task ON team_delivery(task_id, created_at);
`

const AUTHOR = '\u0000'
const SELF_HEADER = `'${selfHeaderPattern(AUTHOR).split(AUTHOR).join("' || coalesce(author_handle, author_kind) || '")}'`

/** Drops the headings agents wrote atop their own posts, which named only the author. */
export const TEAM_MESSAGE_SELF_HEADERS = `
WITH named AS (
  SELECT id, text, regexp_replace(text, ${SELF_HEADER}, '') AS body
  FROM team_message
  WHERE author_kind <> 'task' OR author_handle IS NOT NULL
)
UPDATE team_message SET text = named.body
FROM named
WHERE team_message.id = named.id AND named.body <> named.text AND btrim(named.body, E' \\t\\r\\n') <> '';
`

/** Direct messages: the one member a message goes to, and indexes for each member's reads. */
export const TEAM_DIRECT = `
ALTER TABLE team_message ADD COLUMN to_kind TEXT;
ALTER TABLE team_message ADD COLUMN to_task_id TEXT REFERENCES task(id) ON DELETE SET NULL;
ALTER TABLE team_message ADD COLUMN to_handle TEXT;
CREATE INDEX team_message_to ON team_message(to_task_id, id) WHERE to_kind IS NOT NULL;
CREATE INDEX team_message_public ON team_message(id) WHERE to_kind IS NULL;
`

/** Drops direct messages the EA search index took in before it learned to leave them out. */
export const EA_DOC_NO_DIRECT = `
DELETE FROM ea_doc d USING task_message m
WHERE d.message_id = m.id AND m.kind = 'input'
  AND (m.payload::json ->> 'source') = 'team' AND (m.payload::json ->> 'kind') = 'direct';
`
