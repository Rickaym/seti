/**
 * The evidence ledger: one row per source item an agent read, pointing at the tool result in its
 * transcript that holds the text. Rows go with the transcript row and with the agent.
 */
export const SOURCE_ITEMS = `
CREATE TABLE source_item (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id TEXT NOT NULL REFERENCES task(id) ON DELETE CASCADE,
  message_id BIGINT NOT NULL REFERENCES task_message(id) ON DELETE CASCADE,
  call_id TEXT NOT NULL,
  kind TEXT NOT NULL,
  container TEXT NOT NULL,
  ref TEXT NOT NULL,
  permalink TEXT NOT NULL DEFAULT '',
  item_at TEXT,
  spans TEXT NOT NULL
);
CREATE INDEX source_item_ref ON source_item(task_id, ref text_pattern_ops);
CREATE INDEX source_item_message ON source_item(message_id);
`
