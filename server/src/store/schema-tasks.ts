/**
 * One-shot waits for an agent's turn to end: who waits, an agent or the EA when waiter_id is
 * NULL, and on whom. Seti drops each wait once it delivers the turn's end.
 */
export const AGENT_WAITS = `
CREATE TABLE agent_wait (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  waiter_id TEXT REFERENCES task(id) ON DELETE CASCADE,
  target_id TEXT NOT NULL REFERENCES task(id) ON DELETE CASCADE,
  created_at TEXT NOT NULL
);
CREATE UNIQUE INDEX agent_wait_pair ON agent_wait (COALESCE(waiter_id, ''), target_id);
CREATE INDEX agent_wait_target ON agent_wait (target_id);
CREATE INDEX agent_wait_waiter ON agent_wait (waiter_id);
`

