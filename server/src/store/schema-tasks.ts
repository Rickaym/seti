/**
 * Seti control becomes a level: agents with it on keep Full, the rest act on themselves (Self),
 * which new agents get too. The old switch is cleared rather than dropped, so a release from
 * before levels still runs on this schema and sees every agent without Seti control.
 */
export const TASK_SETI_LEVEL = `
ALTER TABLE task ADD COLUMN seti_level TEXT NOT NULL DEFAULT 'self'
  CHECK (seti_level IN ('off', 'self', 'full'));
UPDATE task SET seti_level = 'full' WHERE seti_control;
UPDATE task SET seti_control = false WHERE seti_control;
`

/** The user's own messages in a task, so stepping to the nearest one far back is one index probe. */
