/** Thinking token estimates crowded visible rows out of transcript pages; nothing reads them. */
export const DROP_THINKING_ESTIMATES = `
DELETE FROM task_message
WHERE kind = 'sdk' AND payload::json->>'type' = 'system' AND payload::json->>'subtype' = 'thinking_tokens';
`

/** Plain directories added to a task, and every worktree Seti made for one, attached or not. */
export const TASK_DIRS = `
CREATE TABLE task_dir (
  task_id TEXT NOT NULL REFERENCES task(id) ON DELETE CASCADE,
  dir TEXT NOT NULL,
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  PRIMARY KEY (task_id, dir)
);

CREATE TABLE task_worktree (
  task_id TEXT NOT NULL REFERENCES task(id) ON DELETE CASCADE,
  repo_id TEXT NOT NULL REFERENCES repo(id) ON DELETE CASCADE,
  dir TEXT NOT NULL,
  PRIMARY KEY (task_id, dir)
);
CREATE INDEX task_worktree_repo ON task_worktree(repo_id);
`

/** Records the worktrees of tasks made with the worktree switch, before Seti kept them per repo. */
export const TASK_WORKTREE_BACKFILL = `
INSERT INTO task_worktree (task_id, repo_id, dir)
SELECT id, repo_id, cwd FROM task WHERE worktree = 1 AND repo_id IS NOT NULL
UNION
SELECT tr.task_id, tr.repo_id, tr.dir FROM task_repo tr JOIN task t ON t.id = tr.task_id WHERE t.worktree = 1
ON CONFLICT DO NOTHING;
`

