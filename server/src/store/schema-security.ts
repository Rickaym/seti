/** Secrets the user manages in Settings, sealed with the key from the secret-key credential. */
export const SECRETS = `
CREATE TABLE secret (
  name TEXT PRIMARY KEY,
  sealed TEXT NOT NULL,
  source TEXT NOT NULL,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
`

/** AWS for sandboxed tasks: the per-task switch and the role Seti assumes for them. */
export const SANDBOX_AWS = `
ALTER TABLE task ADD COLUMN aws BOOLEAN NOT NULL DEFAULT false;

CREATE TABLE aws_settings (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  role_arn TEXT,
  external_id TEXT,
  region TEXT NOT NULL,
  session_minutes INTEGER NOT NULL,
  updated_at TEXT NOT NULL
);
`

/** SSH for sandboxed tasks: the task switch, the agents' ssh config, keys and host keys. */
export const SANDBOX_SSH = `
ALTER TABLE task ADD COLUMN ssh BOOLEAN NOT NULL DEFAULT false;

CREATE TABLE ssh_settings (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  config TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE ssh_key (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  type TEXT NOT NULL,
  public_key TEXT NOT NULL,
  fingerprint TEXT NOT NULL UNIQUE,
  source TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE ssh_known_host (
  host TEXT NOT NULL,
  key_type TEXT NOT NULL,
  public_key TEXT NOT NULL,
  fingerprint TEXT NOT NULL,
  accepted_at TEXT NOT NULL,
  PRIMARY KEY (host, key_type)
);
`

/** Saved Claude logins: names and Claude Code's account identity; tokens stay in the secret store. */
export const CLAUDE_LOGINS = `
CREATE TABLE claude_login (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  identity TEXT NOT NULL UNIQUE,
  email TEXT,
  organization TEXT,
  plan TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE UNIQUE INDEX claude_login_name ON claude_login(lower(name));
`

/** Allow, ask and deny rules for agents, the tool calls waiting on the user, and why one waits. */
export const PERMISSIONS = `
CREATE TABLE permission_rule (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id TEXT REFERENCES task(id) ON DELETE CASCADE,
  behavior TEXT NOT NULL CHECK (behavior IN ('allow', 'ask', 'deny')),
  rule TEXT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE UNIQUE INDEX permission_rule_scope ON permission_rule (COALESCE(task_id, ''), behavior, rule);
CREATE INDEX permission_rule_task ON permission_rule (task_id);

CREATE TABLE permission_request (
  id TEXT PRIMARY KEY,
  task_id TEXT NOT NULL REFERENCES task(id) ON DELETE CASCADE,
  tool_name TEXT NOT NULL,
  summary TEXT NOT NULL,
  input TEXT NOT NULL,
  reason TEXT,
  suggestions TEXT NOT NULL DEFAULT '[]',
  state TEXT NOT NULL DEFAULT 'pending',
  message TEXT,
  created_at TEXT NOT NULL,
  decided_at TEXT
);
CREATE INDEX permission_request_task ON permission_request (task_id, created_at);
CREATE INDEX permission_request_pending ON permission_request (task_id) WHERE state = 'pending';

ALTER TABLE task ADD COLUMN blocked TEXT;
`

/** API keys agents see as placeholder variables, and which credential sets expose each one. */
export const SECRET_ENV = `
ALTER TABLE secret ADD COLUMN env TEXT, ADD COLUMN hosts TEXT[], ADD COLUMN placeholder TEXT UNIQUE;

CREATE TABLE credential_profile_secret (
  profile_id TEXT NOT NULL REFERENCES credential_profile(id) ON DELETE CASCADE,
  secret TEXT NOT NULL REFERENCES secret(name) ON DELETE CASCADE,
  PRIMARY KEY (profile_id, secret)
);
CREATE INDEX credential_profile_secret_secret ON credential_profile_secret(secret);
`
