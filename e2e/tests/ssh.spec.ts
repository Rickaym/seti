import { randomUUID } from 'node:crypto'
import fs from 'node:fs'
import type { AuditPage, SshStatus, TaskAccessView } from '@seti/shared'
import { openAgentSettings } from './support/agent-settings.js'
import { openSeedDb } from './support/db.js'
import { paths } from './support/env.js'
import { apiData, expect, test, toasts } from './support/fixtures.js'
import { addHost, addKey, clearSsh, keyFile } from './support/ssh.js'

test.describe('sandboxed ssh', () => {
  test.use({ allowedHttpStatuses: [400, 409] })

  test.afterEach(async ({ request }) => {
    await clearSsh(request)
  })

  test('keys are added once and hosts select them, with a user and a jump host', async ({ page, request }) => {
    await page.goto('/#settings/ssh')
    const main = page.getByRole('main')
    const keys = main.getByRole('region', { name: 'SSH keys' })
    await expect(keys).toContainText('No keys yet.')
    const newKey = page.getByRole('dialog', { name: 'New SSH key' })
    await keys.getByRole('button', { name: 'New SSH key' }).click()
    await newKey.getByLabel('Key name').fill('e2e main')
    await newKey.getByLabel('Key comment').fill('ops@e2e-host')
    await newKey.getByRole('button', { name: 'Generate' }).click()
    await expect(toasts(page).filter({ hasText: 'Key generated' })).toBeVisible()
    await expect(newKey).toBeHidden()
    await expect(keys.getByRole('listitem', { name: 'e2e main' })).toContainText('Generated by Seti. Unused')
    await keys.getByRole('button', { name: 'e2e main', exact: true }).click()
    await expect(page).toHaveURL(/#settings\/ssh\/keys\/[\w-]+$/)
    await expect(main.getByLabel('Public key of e2e main')).toHaveValue(/^ssh-ed25519 \S+ ops@e2e-host$/)
    await expect(main.getByRole('region', { name: 'Hosts' })).toContainText('No host logs in with this key yet.')
    await main.getByRole('button', { name: 'Back to SSH' }).click()

    const pasted = fs.readFileSync(keyFile('pasted'), 'utf8')
    await keys.getByRole('button', { name: 'New SSH key' }).click()
    await newKey.getByLabel('Key source').selectOption('paste')
    await newKey.getByLabel('Key name').fill('e2e pasted')
    await newKey.getByLabel('Private key', { exact: true }).fill(pasted)
    await newKey.getByRole('button', { name: 'Import' }).click()
    await expect(toasts(page).filter({ hasText: 'Key imported' })).toBeVisible()

    const onDisk = keyFile('on-disk')
    await keys.getByRole('button', { name: 'New SSH key' }).click()
    await newKey.getByLabel('Key source').selectOption('file')
    await expect(newKey.getByLabel('Key comment')).toHaveCount(0)
    await newKey.getByLabel('Key name').fill('e2e file')
    await newKey.getByLabel('Key file').fill(onDisk)
    await newKey.getByRole('button', { name: 'Add' }).click()
    await expect(toasts(page).filter({ hasText: 'Key added' })).toBeVisible()
    await expect(keys.getByRole('listitem', { name: 'e2e file' })).toContainText(`Read from ${onDisk}`)
    await expect(page.locator('body')).not.toContainText('PRIVATE KEY')

    await expect(page).toHaveURL(/#settings\/ssh$/)
    await expect(main.getByRole('region', { name: 'SSH hosts' })).toContainText('No hosts yet.')
    await expect(main).toContainText('Each host logs in as one user with one key.')
    await main.getByRole('button', { name: 'New SSH host' }).click()
    let dialog = page.getByRole('dialog', { name: 'New SSH host' })
    await dialog.getByLabel('Host name').fill('203.0.113.9')
    await dialog.getByLabel('User').fill('ops')
    await dialog.getByLabel('Alias').fill('jump')
    await dialog.getByLabel('SSH key', { exact: true }).selectOption({ label: 'e2e main' })
    await dialog.getByRole('button', { name: 'Add' }).click()
    await expect(page).toHaveURL(/#settings\/ssh\/jump$/)
    await expect(main.getByRole('heading', { name: 'jump', level: 2 })).toBeVisible()
    await main.getByRole('button', { name: 'Back to SSH' }).click()

    await main.getByRole('button', { name: 'New SSH host' }).click()
    dialog = page.getByRole('dialog', { name: 'New SSH host' })
    await dialog.getByLabel('SSH key', { exact: true }).selectOption({ label: 'e2e main' })
    await dialog.getByLabel('Host name').fill('192.0.2.9')
    await dialog.getByLabel('User').fill('ubuntu')
    await dialog.getByLabel('Alias').fill('k8s')
    await dialog.getByLabel('Jump host').selectOption('jump')
    await dialog.getByRole('button', { name: 'Add' }).click()
    await expect(main.getByRole('heading', { name: 'k8s', level: 2 })).toBeVisible()
    await expect(main).toContainText('192.0.2.9:22 via jump')

    const host = main.getByRole('region', { name: 'Connection', exact: true })
    await expect(host.getByLabel('User')).toHaveValue('ubuntu')
    await host.getByRole('button', { name: 'Option' }).click()
    await host.getByLabel('Option 1 value').fill('soon')
    await host.getByRole('button', { name: 'Save' }).click()
    await expect(toasts(page).filter({ hasText: 'ServerAliveInterval soon is not valid' })).toBeVisible()
    await host.getByLabel('Option 1 value').fill('30')
    await host.getByLabel('Port').fill('2222')
    await host.getByLabel('SSH key', { exact: true }).selectOption({ label: 'e2e file' })
    await host.getByRole('button', { name: 'Save' }).click()
    await expect(toasts(page).filter({ hasText: 'k8s saved' })).toBeVisible()
    await expect(main).toContainText('192.0.2.9:2222 via jump')
    const status = await apiData<SshStatus>(request, '/ssh')
    expect(status.hosts.find((entry) => entry.alias === 'k8s')).toMatchObject({
      port: 2222,
      user: 'ubuntu',
      key_name: 'e2e file',
      jump: 'jump',
      options: [{ name: 'ServerAliveInterval', value: '30' }],
    })
    expect(JSON.stringify(status)).not.toContain('PRIVATE KEY')

    const unsafe = await request.post('/api/ssh/hosts', {
      data: {
        alias: 'evil',
        hostname: '203.0.113.5',
        user: 'ops',
        key_id: status.keys[0]?.id ?? '',
        options: [{ name: 'ProxyCommand', value: 'nc' }],
      },
    })
    expect(unsafe.status()).toBe(400)
    expect(await unsafe.text()).toContain('ProxyCommand is not allowed')

    await main.getByRole('button', { name: 'Back to SSH' }).click()
    const hosts = main.getByRole('list', { name: 'SSH hosts' })
    const k8s = hosts.getByRole('listitem', { name: 'k8s' })
    await expect(k8s).toContainText('ubuntu@192.0.2.9:2222 via jump')
    await expect(k8s).toContainText('No trusted host key yet: check it')
    await expect(
      hosts.getByRole('listitem', { name: 'jump' }).getByRole('button', { name: 'Key e2e main' }),
    ).toBeVisible()
    await k8s.getByRole('button', { name: 'Key e2e file' }).click()
    await expect(main.getByRole('heading', { name: 'e2e file', level: 2 })).toBeVisible()
    const users = main.getByRole('list', { name: 'Hosts using e2e file' })
    await expect(users.getByRole('listitem')).toHaveCount(1)
    await expect(users).toContainText('ubuntu@192.0.2.9:2222 via jump')
    await users.getByRole('button', { name: /k8s/ }).click()
    await expect(main.getByRole('heading', { name: 'k8s', level: 2 })).toBeVisible()

    await main.getByRole('button', { name: 'Back to SSH' }).click()
    const mainKey = keys.getByRole('listitem', { name: 'e2e main' })
    await expect(mainKey).toContainText('Used by 1 host: jump')
    await mainKey.getByRole('link', { name: 'jump' }).click()
    await expect(page).toHaveURL(/#settings\/ssh\/jump$/)
    await page.goBack()
    await keys.getByRole('button', { name: 'e2e main', exact: true }).click()
    await main.getByRole('button', { name: 'Remove', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Remove' }).click()
    await expect(toasts(page).filter({ hasText: 'jump uses e2e main; choose another key there first' })).toBeVisible()
    await main.getByRole('button', { name: 'Back to SSH' }).click()
    await keys.getByRole('button', { name: 'e2e pasted', exact: true }).click()
    await main.getByRole('button', { name: 'Remove', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Remove' }).click()
    await expect(toasts(page).filter({ hasText: 'e2e pasted removed' })).toBeVisible()
    await expect(page).toHaveURL(/#settings\/ssh$/)
    await expect(keys.getByRole('listitem', { name: 'e2e pasted' })).toHaveCount(0)
    const audit = await apiData<AuditPage>(request, '/audit?kind=system.ssh_key_added&limit=5')
    expect(JSON.stringify(audit)).not.toContain('PRIVATE KEY')

    await hosts.getByRole('listitem', { name: 'k8s' }).getByRole('button', { name: /k8s/ }).click()
    await main.getByRole('button', { name: 'Delete', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Delete' }).click()
    await expect(toasts(page).filter({ hasText: 'Deleted k8s' })).toBeVisible()
    await expect(page).toHaveURL(/#settings\/ssh$/)
    await expect(hosts.getByRole('listitem')).toHaveCount(1)
  })

  test('the host form puts the key first, requires it and makes a new key inline', async ({ page, request }) => {
    await page.goto('/#settings/ssh')
    const main = page.getByRole('main')
    await main.getByRole('button', { name: 'New SSH host' }).click()
    const dialog = page.getByRole('dialog', { name: 'New SSH host' })
    const fields = dialog.locator('span.font-medium')
    await expect(fields).toHaveText(['SSH key', 'Host name', 'User', 'Port', 'Alias', 'Jump host'])
    await expect(dialog).toContainText('One host logs in as one user with one key')
    const key = dialog.getByLabel('SSH key', { exact: true })
    await expect(key).toHaveValue('new')
    await dialog.getByLabel('Host name').fill('203.0.113.31')
    await dialog.getByLabel('User').fill('ops')
    await dialog.getByLabel('Alias').fill('fresh')
    const add = dialog.getByRole('button', { name: 'Add' })
    await expect(add).toBeDisabled()
    await dialog.getByLabel('New key name').fill('e2e inline')
    await expect(dialog.getByLabel('Private key', { exact: true })).toHaveCount(0)
    await dialog.getByRole('switch', { name: 'Paste a private key' }).click()
    await expect(dialog.getByLabel('Private key', { exact: true })).toBeVisible()
    await dialog.getByRole('switch', { name: 'Paste a private key' }).click()
    await expect(add).toBeEnabled()
    await add.click()
    await expect(main.getByRole('heading', { name: 'fresh', level: 2 })).toBeVisible()
    const status = await apiData<SshStatus>(request, '/ssh')
    const inline = status.keys.find((entry) => entry.name === 'e2e inline')
    expect(inline).toMatchObject({ source: 'generated', hosts: ['fresh'] })
    expect(status.hosts).toMatchObject([{ alias: 'fresh', key_id: inline?.id, key_name: 'e2e inline' }])

    await page.goto(`/#settings/ssh/keys/${inline?.id ?? ''}`)
    await main.getByRole('button', { name: 'Add host with this key' }).click()
    const again = page.getByRole('dialog', { name: 'New SSH host' })
    await expect(again.getByLabel('SSH key', { exact: true })).toHaveValue(inline?.id ?? 'none')
    await expect(again.getByRole('option', { name: 'Choose a key' })).toHaveCount(0)
    await again.getByLabel('Host name').fill('203.0.113.32')
    await again.getByLabel('User').fill('ops')
    await again.getByLabel('Alias').fill('second')
    await again.getByRole('button', { name: 'Add' }).click()
    await expect(main.getByRole('heading', { name: 'second', level: 2 })).toBeVisible()
    await page.goto(`/#settings/ssh/keys/${inline?.id ?? ''}`)
    await expect(main.getByRole('list', { name: 'Hosts using e2e inline' }).getByRole('listitem')).toHaveCount(2)
  })

  test('a key swapped once changes for every host that selects it', async ({ page, request }) => {
    const key = await addKey(request, 'e2e shared')
    await addHost(request, 'one', '203.0.113.21', { key_id: key.id })
    await addHost(request, 'two', '203.0.113.22', { key_id: key.id })
    await page.goto('/#settings/ssh')
    const main = page.getByRole('main')
    const keys = main.getByRole('region', { name: 'SSH keys' })
    await expect(keys.getByRole('listitem', { name: 'e2e shared' })).toContainText('Used by 2 hosts: one, two')

    await keys.getByRole('button', { name: 'e2e shared', exact: true }).click()
    await expect(main.getByRole('list', { name: 'Hosts using e2e shared' }).getByRole('listitem')).toHaveCount(2)
    await main.getByRole('heading', { name: 'e2e shared', level: 2 }).dblclick()
    const rename = main.getByLabel('New name')
    await rename.fill('e2e discarded')
    await rename.blur()
    await expect(main.getByRole('heading', { name: 'e2e shared', level: 2 })).toBeVisible()
    await main.getByRole('button', { name: 'Rename key' }).click()
    await rename.fill('e2e rotated')
    await rename.press('Enter')
    await expect(toasts(page).filter({ hasText: 'Renamed to e2e rotated' })).toBeVisible()
    await expect(main.getByRole('heading', { name: 'e2e rotated', level: 2 })).toBeVisible()

    await main.getByRole('button', { name: 'Swap' }).click()
    const dialog = page.getByRole('dialog', { name: 'Swap e2e rotated' })
    await expect(dialog).toContainText('one, two log in with it.')
    await dialog.getByLabel('Private key', { exact: true }).fill(fs.readFileSync(keyFile('swap'), 'utf8'))
    await dialog.getByRole('button', { name: 'Swap' }).click()
    await expect(toasts(page).filter({ hasText: 'e2e rotated swapped' })).toBeVisible()
    await expect(main).toContainText('Pasted, sealed by Seti')

    const status = await apiData<SshStatus>(request, '/ssh')
    const swapped = status.keys.find((entry) => entry.id === key.id)
    expect(swapped?.fingerprint).not.toBe(key.fingerprint)
    expect(status.hosts.map((host) => [host.alias, host.key_id, host.key_name])).toEqual([
      ['one', key.id, 'e2e rotated'],
      ['two', key.id, 'e2e rotated'],
    ])
  })

  test('a host is renamed in place with its sets and the hosts jumping through it', async ({ page, request }) => {
    const key = await addKey(request, 'e2e rename')
    await addHost(request, 'jump', '203.0.113.9', { key_id: key.id })
    await addHost(request, 'k8s', '198.51.100.9', { key_id: key.id, jump: 'jump' })
    await request.put('/api/credentials/profiles/default/ssh-hosts/jump', { data: {} })
    await page.goto('/#settings/ssh/jump')
    const main = page.getByRole('main')
    await main.getByRole('button', { name: 'Rename host' }).click()
    const rename = main.getByLabel('New name')
    await expect(main).toContainText('Agents use the new name from their next turn.')
    await rename.fill('k8s')
    await rename.press('Enter')
    await expect(toasts(page).filter({ hasText: 'There is already an ssh host k8s' })).toBeVisible()
    await rename.press('Escape')
    await expect(rename).toHaveCount(0)

    await main.getByRole('heading', { name: 'jump', level: 2 }).dblclick()
    await rename.fill('bastion')
    await rename.press('Enter')
    await expect(page).toHaveURL(/#settings\/ssh\/bastion$/)
    await expect(main.getByRole('heading', { name: 'bastion', level: 2 })).toBeVisible()
    await expect(toasts(page).filter({ hasText: 'Renamed to bastion' })).toBeVisible()
    const status = await apiData<SshStatus>(request, '/ssh')
    expect(status.hosts.map((host) => [host.alias, host.jump, host.sets.map((set) => set.name)])).toEqual([
      ['bastion', null, ['Default']],
      ['k8s', 'bastion', []],
    ])
    await main.getByRole('button', { name: 'Back to SSH' }).click()
    await expect(main.getByRole('list', { name: 'SSH hosts' }).getByRole('listitem', { name: 'k8s' })).toContainText(
      'via bastion',
    )
  })

  test('an agent gets a host on its own or through its credential', async ({ page, request }) => {
    const key = await addKey(request, 'e2e ops')
    await addHost(request, 'jump', '203.0.113.9', { key_id: key.id })
    await addHost(request, 'k8s', '198.51.100.9', { key_id: key.id, jump: 'jump' })
    await addHost(request, 'db', '198.51.100.7', { key_id: key.id })
    const db = openSeedDb()
    const id = randomUUID()
    const ts = new Date().toISOString()
    await db.run(
      `INSERT INTO task (id, title, repo_id, cwd, worktree, sandbox, status, created_at, updated_at)
       VALUES (?, ?, NULL, ?, 0, 1, 'idle', ?, ?)`,
      id,
      `E2E ssh ${id.slice(0, 8)}`,
      paths.checkout,
      ts,
      ts,
    )
    await db.close()

    await page.goto('/#settings/ssh')
    const hosts = page.getByRole('main').getByRole('list', { name: 'SSH hosts' })
    const jumpDefault = hosts.getByRole('switch', { name: 'jump on by default' })
    await expect(jumpDefault).not.toBeChecked()
    await jumpDefault.click()
    await expect(toasts(page).filter({ hasText: 'jump is on by default' })).toBeVisible()
    await expect(jumpDefault).toBeChecked()

    await page.goto('/#settings/credentials/default')
    const bundled = page.getByRole('main').getByRole('region', { name: 'SSH hosts' })
    await bundled.getByRole('switch', { name: 'db in Default' }).click()
    await expect(toasts(page).filter({ hasText: 'Default agents get db' })).toBeVisible()
    await expect(bundled.getByRole('switch', { name: 'db in Default' })).toBeChecked()

    await page.goto(`/#agents/${id}`)
    await openAgentSettings(page, 'Access')
    await page.getByRole('button', { name: 'Edit access' }).click()
    const access = page.getByRole('dialog', { name: /^Access of / })
    const ssh = access.getByRole('region', { name: 'SSH hosts' })
    const row = (alias: string) =>
      ssh.getByRole('listitem').filter({ has: page.getByRole('switch', { name: alias, exact: true }) })
    await expect(row('jump')).toContainText('Inherited')
    await expect(row('db')).toContainText('From Default')
    await expect(ssh.getByRole('switch', { name: 'db', exact: true })).toBeChecked()
    await expect(ssh.getByRole('switch', { name: 'db', exact: true })).toBeDisabled()
    await ssh.getByRole('switch', { name: 'k8s', exact: true }).click()
    await expect(row('k8s')).toContainText('Custom')
    await expect(row('k8s')).toContainText('198.51.100.9:22 via jump')
    const view = await apiData<TaskAccessView>(request, `/tasks/${id}/access`)
    expect(view.items.filter((item) => item.kind === 'ssh')).toMatchObject([
      { id: 'db', enabled: true, in_set: true, override: null, missing_key: [] },
      { id: 'jump', enabled: true, in_set: false, missing_key: [] },
      { id: 'k8s', enabled: true, in_set: false, override: true, missing_key: [] },
    ])
    await page.keyboard.press('Escape')

    await request.delete('/api/credentials/profiles/default/ssh-hosts/db')
    const after = await apiData<TaskAccessView>(request, `/tasks/${id}/access`)
    expect(after.items.find((item) => item.id === 'db')).toMatchObject({ enabled: false, in_set: false })
  })
})
